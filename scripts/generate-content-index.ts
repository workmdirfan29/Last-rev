/**
 * Generates src/data/questions/index.generated.ts — a lightweight index of
 * every question (id, title, topic, difficulty, keywords) so the app can show
 * counts, lists and global search without loading answer bodies.
 *
 *   pnpm content:index
 *
 * Question files are the single source of truth; never edit the index by hand.
 */
import { readdirSync, writeFileSync, statSync } from "node:fs"
import { join, resolve } from "node:path"
import { pathToFileURL } from "node:url"
import {
  EXPERIENCE_LEVELS,
  type Question,
  type QuestionIndexEntry,
} from "../src/types/content.ts"

const root = resolve(import.meta.dirname, "../src/data/questions")
const entries: QuestionIndexEntry[] = []

for (const moduleId of readdirSync(root).sort()) {
  const dir = join(root, moduleId)
  if (!statSync(dir).isDirectory()) continue
  for (const level of EXPERIENCE_LEVELS) {
    const file = join(dir, `${level}.ts`)
    try {
      statSync(file)
    } catch {
      continue
    }
    const mod = (await import(pathToFileURL(file).href)) as {
      default: Question[]
    }
    for (const q of mod.default) {
      entries.push({
        id: q.id,
        moduleId: q.moduleId,
        level: q.level,
        topic: q.topic,
        difficulty: q.difficulty,
        title: q.title,
        keywords: q.keywords,
        estimatedMinutes: q.estimatedMinutes,
      })
    }
  }
}

const out = `// AUTO-GENERATED by scripts/generate-content-index.ts — do not edit by hand.
// Run \`pnpm content:index\` after adding or changing question files.
import type { QuestionIndexEntry } from "@/types/content"

export const QUESTION_INDEX: QuestionIndexEntry[] = ${JSON.stringify(entries, null, 2)}
`
writeFileSync(join(root, "index.generated.ts"), out)
console.log(`Indexed ${entries.length} questions`)
