/**
 * Generates src/data/english/index.generated.ts: one light record per lesson (title, item ids, counts) so
 * the course page, the landing card and the 30-day challenge can render without loading lesson bodies.
 *
 *   pnpm english:index
 *
 * Lesson files are the single source of truth; never edit the index by hand.
 */
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { pathToFileURL } from "node:url"
import { ENGLISH_MODULES } from "../src/data/english/modules.ts"
import {
  ITEM_KINDS,
  type EnglishLesson,
  type EnglishLessonIndexEntry,
} from "../src/types/english.ts"

const root = resolve(import.meta.dirname, "../src/data/english")
const entries: EnglishLessonIndexEntry[] = []

async function read(file: string): Promise<EnglishLesson[]> {
  return (
    (await import(pathToFileURL(file).href)) as { default: EnglishLesson[] }
  ).default
}
function add(category: string, lessons: EnglishLesson[]) {
  for (const l of lessons) {
    const counts = Object.fromEntries(
      ITEM_KINDS.map((k) => [k, 0])
    ) as EnglishLessonIndexEntry["counts"]
    for (const it of l.items) counts[it.kind]++
    entries.push({
      id: l.id,
      moduleId: l.moduleId,
      slug: l.slug,
      category,
      title: l.title,
      titleHi: l.titleHi,
      goal: l.goal,
      itemIds: l.items.map((i) => i.id),
      itemKinds: l.items.map((i) => i.kind),
      counts,
    })
  }
}

for (const m of ENGLISH_MODULES) {
  if (m.layout === "file") {
    const file = join(root, `${m.id}.ts`)
    if (existsSync(file)) add("", await read(file))
  } else {
    const dir = join(root, m.id)
    if (!existsSync(dir) || !statSync(dir).isDirectory()) continue
    for (const f of readdirSync(dir).sort()) {
      if (!f.endsWith(".ts")) continue
      add(f.replace(/\.ts$/, ""), await read(join(dir, f)))
    }
  }
}

const out = `// AUTO-GENERATED by scripts/generate-english-index.ts — do not edit by hand.
// Run \`pnpm english:index\` after adding or changing lesson files.
import type { EnglishLessonIndexEntry } from "../../types/english"

export const ENGLISH_INDEX: EnglishLessonIndexEntry[] = ${JSON.stringify(entries, null, 2)}
`
writeFileSync(join(root, "index.generated.ts"), out)
console.log(`Indexed ${entries.length} English lessons`)
