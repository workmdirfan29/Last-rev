/**
 * Generates src/data/lessons/index.generated.ts: one light record per Study Zone lesson (title, topic, minutes,
 * check items, exercises) so the roadmap, lesson library, plan, builder and counts render without loading
 * lesson bodies.
 *
 *   pnpm lessons:index
 *
 * Lesson files are the single source of truth; never edit the index by hand.
 */
import { readdirSync, statSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { pathToFileURL } from "node:url"
import { topicIdOf } from "../src/utils/topic-id.ts"
import {
  LESSON_FILE_PATTERN,
  type StudyLesson,
  type StudyLessonIndexEntry,
} from "../src/types/lesson.ts"

const root = resolve(import.meta.dirname, "../src/data/lessons")
const entries: StudyLessonIndexEntry[] = []

for (const moduleId of readdirSync(root).sort()) {
  const dir = join(root, moduleId)
  if (!statSync(dir).isDirectory()) continue
  for (const f of readdirSync(dir).sort()) {
    if (!f.endsWith(".ts")) continue
    const m = LESSON_FILE_PATTERN.exec(f)
    if (!m)
      throw new Error(`${moduleId}/${f}: lesson files are named NN-<slug>.ts`)
    const lesson = (
      (await import(pathToFileURL(join(dir, f)).href)) as {
        default: StudyLesson
      }
    ).default
    if (lesson.moduleId !== moduleId)
      throw new Error(
        `${moduleId}/${f}: defineLesson was given module "${lesson.moduleId}"`
      )
    if (lesson.slug !== m[2])
      throw new Error(
        `${moduleId}/${f}: the file name says "${m[2]}" but the lesson slug is "${lesson.slug}"`
      )
    entries.push({
      id: lesson.id,
      moduleId,
      slug: lesson.slug,
      file: `${moduleId}/${f.replace(/\.ts$/, "")}`,
      order: Number(m[1]),
      title: lesson.title,
      topic: lesson.topic,
      topicId: topicIdOf(moduleId, lesson.topic),
      minutes: lesson.minutes,
      overview: lesson.overview,
      objectives: lesson.objectives.length,
      check: lesson.check.map((c) => ({ id: c.id, type: c.type })),
      assignment: {
        checklist: lesson.assignment.checklist.length,
        minutes: lesson.assignment.minutes,
      },
      exercises: lesson.exercises.map((e) => ({
        slug: e.slug,
        title: e.title,
        language: e.language,
        runnable: Boolean(e.run),
      })),
      prerequisites: lesson.prerequisites,
      resources: lesson.resources.length,
    })
  }
}

const out = `// AUTO-GENERATED by scripts/generate-lessons-index.ts — do not edit by hand.
// Run \`pnpm lessons:index\` after adding or changing lesson files.
import type { StudyLessonIndexEntry } from "../../types/lesson"

export const LESSON_INDEX: StudyLessonIndexEntry[] = ${JSON.stringify(entries, null, 2)}
`
writeFileSync(join(root, "index.generated.ts"), out)
console.log(`Indexed ${entries.length} study lessons`)
