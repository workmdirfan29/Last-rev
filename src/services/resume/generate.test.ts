import { describe, expect, it } from "vitest"
import { MODULE_BY_ID } from "@/data/catalog/modules"
import {
  CAP_PER_SOURCE,
  TEMPLATES,
  TEMPLATE_BY_ID,
} from "@/data/resume/templates"
import { QUESTION_ID_PATTERN } from "@/types/content"
import {
  QUESTION_SET_APP,
  RESUME_SECTIONS,
  type ResumeProfile,
  type ResumeQuestion,
} from "@/types/learner"
import {
  clip,
  generateQuestions,
  isShortEntry,
  isSkillName,
  monthIndex,
  questionId,
  reconcile,
} from "./generate"
import { buildQuestionSet, parseQuestionSet, planImport } from "./question-set"
import { mapSkills } from "./skills"

let n = 0
const u = () => `u${++n}`
const bullet = (text: string) => ({ uid: u(), text })

function profile(over: Partial<ResumeProfile> = {}): ResumeProfile {
  return {
    id: "profile",
    sourceName: "asha.pdf",
    importedAt: "2026-11-04T00:00:00.000Z",
    updatedAt: "2026-11-04T00:00:00.000Z",
    summary:
      "Backend developer with experience building REST services and dashboards.",
    skills: ["Java", "Spring Boot", "SQL", "Docker", "Haskell"].map((name) => ({
      uid: u(),
      group: "",
      name,
    })),
    experiences: [
      {
        uid: u(),
        company: "Example Tech Ltd",
        role: "Software Engineer",
        start: "Jan 2022",
        end: "Present",
        bullets: [
          bullet("Built REST APIs with Spring Boot for the order service."),
          bullet("Reduced report load time by optimising SQL queries."),
          bullet("Mentored two interns on code reviews."),
        ],
      },
      {
        uid: u(),
        company: "Sample Systems Pvt Ltd",
        role: "Junior Developer",
        start: "Jun 2020",
        end: "Dec 2020",
        bullets: [bullet("Maintained an internal dashboard.")],
      },
    ],
    projects: [
      {
        uid: u(),
        name: "Inventory Tracker",
        role: "",
        description: "",
        technologies: ["Java", "Spring Boot", "MySQL"],
        bullets: [bullet("Stock management app with role-based login.")],
      },
    ],
    education: [],
    certifications: [bullet("Example Cloud Practitioner")],
    achievements: [],
    unplaced: [],
    other: [],
    includeDateQuestions: true,
    raiseCaps: false,
    ...over,
  }
}
const opts = { includeDateQuestions: true, raiseCaps: false }
const titles = (p: ResumeProfile, o = opts) =>
  generateQuestions(p, o).map((q) => q.title)

describe("templates", () => {
  it("are unique, belong to a section, and every slot used in the wording has a value in the outline or is a known slot", () => {
    expect(new Set(TEMPLATES.map((t) => t.id)).size).toBe(TEMPLATES.length)
    for (const t of TEMPLATES) {
      expect(RESUME_SECTIONS).toContain(t.section)
      expect(t.framework.length).toBeGreaterThanOrEqual(2)
      expect(
        t.framework.some((f) => /\[[^\]]+\]/.test(f)),
        t.id
      ).toBe(true)
    }
    for (const section of RESUME_SECTIONS)
      expect(
        TEMPLATES.some((t) => t.section === section),
        section
      ).toBe(true)
  })

  it("never claim a fact: no company, number or achievement is written into a template, and none says AI wrote it", () => {
    for (const t of TEMPLATES) {
      expect(t.text, t.id).not.toMatch(
        /\b(AI|artificial|machine|generated by)\b/i
      )
      // a template contains no digits of its own (numbers come only from the learner's words)
      expect(t.text.replace(/\{\w+\}/g, ""), t.id).not.toMatch(/\d/)
    }
    // the stay/leave wording is neutral
    expect(TEMPLATE_BY_ID.get("company.stay")!.text).toBe(
      "What would make you stay at {company} longer?"
    )
    expect(TEMPLATE_BY_ID.has("company.move-on")).toBe(false)
  })
})

describe("generated questions", () => {
  it("are deterministic: the same profile gives the same questions and ids", () => {
    const p = profile()
    expect(generateQuestions(p, opts)).toEqual(generateQuestions(p, opts))
  })

  it("fill slots only with the learner's own words and skip a template whose slot is empty", () => {
    const t = titles(profile())
    expect(t).toContain(
      "What was your role at Example Tech Ltd, and what did a typical week look like?"
    )
    expect(t).toContain(
      "Tell me about Inventory Tracker: what problem did it solve and who used it?"
    )
    expect(t).toContain("What made Java a good fit for Inventory Tracker?")
    expect(t).toContain("You list Java. Describe a problem you solved with it.")
    // a job with no company has no company questions, a project with no technologies has no architecture questions
    const p = profile()
    p.experiences[1].company = ""
    p.projects[0].technologies = []
    const t2 = titles(p)
    expect(t2.some((x) => x.includes("Sample Systems"))).toBe(false)
    expect(
      t2.some((x) => x.startsWith("Walk me through the architecture"))
    ).toBe(false)
    expect(t2).toContain(
      "Tell me about Inventory Tracker: what problem did it solve and who used it?"
    )
    expect(
      generateQuestions(
        profile({
          experiences: [],
          projects: [],
          skills: [],
          summary: "",
          certifications: [],
          achievements: [],
        }),
        opts
      )
    ).toEqual([])
  })

  it("has no duplicate ids or wording, and every id is valid for the question routes and outside the catalogue modules' own ids", () => {
    const qs = generateQuestions(profile(), opts)
    expect(new Set(qs.map((q) => q.id)).size).toBe(qs.length)
    expect(new Set(qs.map((q) => q.title.toLowerCase())).size).toBe(qs.length)
    for (const q of qs) {
      expect(q.id, q.id).toMatch(QUESTION_ID_PATTERN)
      const mod = q.id.split(".")[0]
      expect(MODULE_BY_ID.get(mod)?.skillArea, mod).toBe("hr")
      expect(mod).toBe(`resume-${q.section}`)
    }
  })

  it("cuts long bullets at a word with an ellipsis", () => {
    const long =
      "Built " +
      "a very detailed and extensive internal reporting platform for many teams ".repeat(
        5
      )
    const c = clip(long)
    expect(c.length).toBeLessThanOrEqual(141)
    expect(c.endsWith("…")).toBe(true)
    expect(c).not.toMatch(/ …$/)
    expect(clip("Short one.")).toBe("Short one")
  })

  it("separates achievements (numbers or achievement verbs) from responsibilities, with the per-source cap that can be lifted", () => {
    const p = profile()
    p.experiences[0].bullets = Array.from({ length: 8 }, (_, i) =>
      bullet(
        `Handled routine task number ${["alpha", "beta", "gamma", "delta", "epsilon", "zeta", "eta", "theta"][i]} for the team.`
      )
    )
    const capped = titles(p).filter((x) => x.includes("Handled routine task"))
    expect(capped).toHaveLength(CAP_PER_SOURCE)
    const raised = titles(p, { ...opts, raiseCaps: true }).filter((x) =>
      x.includes("Handled routine task")
    )
    expect(raised).toHaveLength(8)
    // an achievement gets "how" and "proof"
    const q = titles(profile()).filter(
      (x) =>
        x.includes("Reduced report load time") && !x.startsWith("You mention")
    )
    expect(q).toHaveLength(2)
  })

  it("makes follow-ups only for technologies mentioned in a bullet", () => {
    const t = titles(profile())
    expect(t.some((x) => x.startsWith("You mention Spring Boot in"))).toBe(true)
    expect(t.some((x) => x.includes("You mention Haskell"))).toBe(false)
  })

  it("derives difficult questions from the data: unused skills, short tenure, gaps, no numbers, many skills", () => {
    const t = titles(profile())
    expect(t).toContain(
      "You list Haskell, but it does not appear in your experience or projects. Where have you used it?"
    )
    expect(t.some((x) => x.startsWith("You list Java, but"))).toBe(false)
    expect(t).toContain(
      "Your role at Sample Systems Pvt Ltd lasted about 6 months. How would you explain that?"
    )
    expect(t).toContain(
      "There are about 13 months between Sample Systems Pvt Ltd and Example Tech Ltd. What were you doing then?"
    )
    // the date questions can be switched off, and need both dates
    const off = titles(profile(), { ...opts, includeDateQuestions: false })
    expect(
      off.some(
        (x) => x.includes("lasted about") || x.includes("months between")
      )
    ).toBe(false)
    const p = profile()
    p.experiences[1].end = "2020"
    expect(titles(p).some((x) => x.includes("lasted about"))).toBe(false)
    // no numbers anywhere in 3 or more bullets
    const plain = profile()
    plain.experiences[0].bullets = [
      bullet("Built a service."),
      bullet("Wrote tests."),
      bullet("Fixed bugs."),
    ]
    plain.experiences[1].bullets = []
    plain.projects[0].bullets = []
    expect(
      titles(plain).some((x) =>
        x.startsWith("None of your bullets include a number")
      )
    ).toBe(true)
    // too many skills
    const many = profile({
      skills: Array.from({ length: 16 }, (_, i) => ({
        uid: u(),
        group: "",
        name: `Tool${i}`,
      })),
    })
    expect(titles(many)).toContain(
      "Your resume lists 16 skills. Which three would you be comfortable being tested on today?"
    )
  })

  it("uses the current-job and ended-job wording, neutrally", () => {
    const t = titles(profile())
    expect(t).toContain("What would make you stay at Example Tech Ltd longer?")
    expect(t).toContain("Why did you leave Sample Systems Pvt Ltd?")
    expect(t.some((x) => /ready to move on/i.test(x))).toBe(false)
  })

  it("makes scenario questions only for the six technologies the resume mentions most", () => {
    const skills = Array.from({ length: 9 }, (_, i) => ({
      uid: u(),
      group: "",
      name: `Tech${i}`,
    }))
    const p = profile({ skills })
    p.experiences[0].bullets = skills.map((s) =>
      bullet(`Worked with ${s.name} on the team.`)
    )
    const scen = generateQuestions(p, opts).filter(
      (q) => q.section === "scenario"
    )
    expect(new Set(scen.map((q) => q.sourceUid)).size).toBe(6)
    expect(scen).toHaveLength(12)
  })
})

describe("stable ids and regeneration", () => {
  const now = "2026-11-04T10:00:00.000Z"
  const store = (p: ResumeProfile) =>
    reconcile([], generateQuestions(p, opts), now)

  it("keeps an id when the wording of its source is corrected, and re-renders the question", () => {
    const p = profile()
    const before = store(p)
    const b = p.experiences[0].bullets[1]
    const old = before.find(
      (q) =>
        q.title.includes("Reduced report load time") &&
        q.templateId === "ach.how"
    )!
    b.text = "Cut report load time by optimising SQL queries."
    const after = reconcile(before, generateQuestions(p, opts), now)
    const renewed = after.find((q) => q.id === old.id)!
    expect(renewed.title).toContain("Cut report load time")
    expect(renewed.status).toBe("active")
    expect(after).toHaveLength(before.length) // nothing added or lost by a typo fix
  })

  it("marks a question 'source removed' when its source is deleted, and revives it if the source returns", () => {
    const p = profile()
    const before = store(p)
    const gone = p.projects.pop()!
    const after = reconcile(before, generateQuestions(p, opts), now)
    const removed = after.filter((q) => q.status === "source-removed")
    const projectQs = before.filter((q) => q.sourceUid === gone.uid)
    expect(projectQs.length).toBeGreaterThan(0)
    for (const q of projectQs) expect(removed.map((r) => r.id)).toContain(q.id)
    expect(after.length).toBeGreaterThanOrEqual(before.length) // never silently dropped (a newly unused skill may add one)
    p.projects.push(gone)
    const back = reconcile(after, generateQuestions(p, opts), now)
    // the project's own questions are live again (a question that only existed while it was gone is now orphaned)
    const stillGone = new Set(
      back.filter((q) => q.status === "source-removed").map((q) => q.id)
    )
    for (const q of projectQs) expect(stillGone.has(q.id)).toBe(false)
  })

  it("does not overwrite wording the learner edited, and 'reset' can restore the generated text", () => {
    const p = profile()
    const before = store(p)
    const target = before[0]
    const edited: ResumeQuestion[] = before.map((q) =>
      q.id === target.id
        ? { ...q, title: "My own wording of this question", edited: true }
        : q
    )
    const after = reconcile(edited, generateQuestions(p, opts), now)
    const kept = after.find((q) => q.id === target.id)!
    expect(kept.title).toBe("My own wording of this question")
    expect(kept.generatedTitle).toBe(target.title) // what "Reset to generated" restores
  })

  it("leaves imported questions alone and adds only questions it does not have", () => {
    const p = profile()
    const imported: ResumeQuestion = {
      ...store(p)[0],
      id: "resume-intro.fresher.zzzzzzzzzz",
      setId: "set_1",
      setLabel: "friend.json",
    }
    const after = reconcile([imported], generateQuestions(p, opts), now)
    expect(after.find((q) => q.id === imported.id)).toEqual(imported)
    expect(after.length).toBe(1 + generateQuestions(p, opts).length)
  })

  it("makes ids from the template and the item's uid, not its text", () => {
    expect(questionId("project", "project.pitch", "abc", "")).toBe(
      questionId("project", "project.pitch", "abc", "")
    )
    expect(questionId("project", "project.pitch", "abc", "")).not.toBe(
      questionId("project", "project.part", "abc", "")
    )
    expect(questionId("project", "project.pitch", "abc", "")).not.toBe(
      questionId("project", "project.pitch", "abd", "")
    )
  })
})

describe("skill rows and jobs the reader may have got wrong", () => {
  it("makes skill questions only for rows of up to 3 words and 30 characters, never 'You list <a sentence>'", () => {
    expect(isSkillName("Spring Boot")).toBe(true)
    expect(isSkillName("Java")).toBe(true)
    expect(isSkillName("Responsible for building the order service")).toBe(
      false
    )
    expect(isSkillName("A".repeat(31))).toBe(false)
    expect(isSkillName("   ")).toBe(false)
    const sentence = "Built and deployed several services end to end"
    const p = profile({
      skills: [...profile().skills, { uid: u(), group: "", name: sentence }],
    })
    const all = titles(p).join("\n")
    expect(all).not.toContain(sentence)
    expect(all).toContain(
      "You list Java. Describe a problem you solved with it."
    )
    // but it still counts toward "your resume lists N skills"
    const many = profile({
      skills: Array.from({ length: 15 }, (_, i) => ({
        uid: u(),
        group: "",
        name: `Tool${i}`,
      })).concat([{ uid: u(), group: "", name: sentence }]),
    })
    expect(titles(many)).toContain(
      "Your resume lists 16 skills. Which three would you be comfortable being tested on today?"
    )
  })

  it("makes company questions for a job with no bullets, but no responsibility, achievement or follow-up questions", () => {
    const p = profile()
    p.experiences = [
      {
        uid: u(),
        company: "Example Labs",
        role: "Trainee",
        start: "Jun 2023",
        end: "Aug 2023",
        bullets: [],
      },
    ]
    p.projects = []
    const t = titles(p)
    expect(t).toContain(
      "What was your role at Example Labs, and what did a typical week look like?"
    )
    expect(
      t.some(
        (x) =>
          x.startsWith("You wrote:") ||
          x.startsWith("Tell me how you achieved") ||
          x.startsWith("You mention")
      )
    ).toBe(false)
  })

  it("marks a training or internship entry of under 3 months as a short entry, and nothing else", () => {
    const e = (role: string, start: string, end: string) => ({
      role,
      company: "Example Labs",
      start,
      end,
    })
    expect(isShortEntry(e("Intern", "Jun 2023", "Aug 2023"))).toBe(true)
    expect(isShortEntry(e("Trainee Developer", "06/2023", "07/2023"))).toBe(
      true
    )
    expect(isShortEntry(e("Intern", "Jun 2023", "Dec 2023"))).toBe(false) // over 3 months
    expect(isShortEntry(e("Software Engineer", "Jun 2023", "Aug 2023"))).toBe(
      false
    ) // not a training title
    expect(isShortEntry(e("Intern", "2023", "2023"))).toBe(false) // dates too vague to say
  })
})

describe("dates", () => {
  it("reads month and numeric dates, and refuses a bare year as too vague for a gap or tenure", () => {
    expect(monthIndex("Jan 2022")).toBe(2022 * 12 + 1)
    expect(monthIndex("01/2022")).toBe(2022 * 12 + 1)
    expect(monthIndex("March 2020")).toBe(2020 * 12 + 3)
    expect(monthIndex("2019")).toBeNull()
    expect(monthIndex("Present")).toBeNull()
  })
})

describe("skill mapping", () => {
  it("links resume skills to catalogue technologies and their module's questions, and leaves the rest as plain tags", () => {
    const m = mapSkills([
      { uid: "1", group: "", name: "React" },
      { uid: "2", group: "", name: "react" }, // duplicate
      { uid: "3", group: "", name: "Haskell" },
    ])
    expect(m).toHaveLength(2)
    expect(m[0].skill?.id).toBe("react")
    expect(m[0].practise).toMatchObject({ moduleId: "react" })
    expect(m[0].practise!.questions).toBeGreaterThan(0)
    expect(m[1]).toEqual({ name: "Haskell", skill: null, practise: null })
  })
})

describe("question sets", () => {
  const now = new Date("2026-11-04T10:00:00.000Z")
  const p = profile({
    education: [bullet("Example Institute of Technology, 2016")],
    unplaced: [bullet("a line the reader could not place")],
  })
  const qs = reconcile([], generateQuestions(p, opts), now.toISOString())

  it("exports questions only by default: the file holds no part of the resume beyond question wording", () => {
    const set = buildQuestionSet(qs, p, {
      name: "Mine",
      includeProfile: false,
      now,
    })
    expect(set.app).toBe(QUESTION_SET_APP)
    expect(set.profile).toBeUndefined()
    const json = JSON.stringify(set)
    // things on the resume that no question quotes must not be in the file
    expect(json).not.toContain("Example Institute") // education is never quoted by a question
    expect(json).not.toContain("could not place") // nor are unplaced lines
    expect(json).not.toContain("asha.pdf")
    expect(json).not.toContain("Jun 2020")
    expect(json).not.toContain("sourceUid")
    for (const q of set.questions)
      expect(Object.keys(q).sort()).toEqual([
        "edited",
        "framework",
        "id",
        "section",
        "templateId",
        "title",
      ])
  })

  it("includes the profile only when asked", () => {
    expect(
      buildQuestionSet(qs, p, { name: "x", includeProfile: true, now }).profile
        ?.summary
    ).toContain("Backend developer")
  })

  it("leaves out questions whose source was removed", () => {
    const withGone = qs.map((q, i) =>
      i === 0 ? { ...q, status: "source-removed" as const } : q
    )
    expect(
      buildQuestionSet(withGone, p, { name: "x", includeProfile: false, now })
        .questions
    ).toHaveLength(qs.length - 1)
  })

  it("round-trips through a file, validates with Zod, and previews counts and duplicates before anything is written", () => {
    const text = JSON.stringify(
      buildQuestionSet(qs, p, { name: "Mine", includeProfile: false, now })
    )
    const parsed = parseQuestionSet(text)
    expect(parsed.ok).toBe(true)
    if (!parsed.ok) return
    const plan = planImport(parsed.set, [], "mine.json", now.toISOString())
    expect(plan.toAdd).toHaveLength(qs.length)
    expect(plan.duplicates).toBe(0)
    expect(
      plan.toAdd.every(
        (q) =>
          q.setLabel === "mine.json" &&
          q.setId === plan.setId &&
          q.sourceUid === "" &&
          q.status === "active"
      )
    ).toBe(true)
    // importing into a bank that already has them skips every one
    const again = planImport(parsed.set, qs, "mine.json", now.toISOString())
    expect(again.toAdd).toHaveLength(0)
    expect(again.duplicates).toBe(qs.length)
    expect(Object.values(plan.bySection).reduce((a, b) => a + b, 0)).toBe(
      qs.length
    )
  })

  it("rejects files that are not question sets, have a bad id, or are a newer version", () => {
    expect(parseQuestionSet("not json")).toMatchObject({ ok: false })
    expect(parseQuestionSet(JSON.stringify({ app: "other" }))).toMatchObject({
      ok: false,
    })
    const good = buildQuestionSet(qs, p, {
      name: "x",
      includeProfile: false,
      now,
    })
    const bad = {
      ...good,
      questions: [{ ...good.questions[0], id: "react.fresher.what-is-jsx" }],
    }
    const r = parseQuestionSet(JSON.stringify(bad))
    expect(r.ok).toBe(false)
    expect(parseQuestionSet(JSON.stringify({ ...good, version: 2 })).ok).toBe(
      false
    )
  })
})
